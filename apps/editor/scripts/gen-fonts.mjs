/**
 * Generates src/lib/fonts.generated.ts from the installed font packages, so
 * family names, weights and italics always match the real font files.
 *
 * To add a font: add its @fontsource(-variable) package to package.json,
 * add it to LIST below, then run `pnpm --filter editor gen:fonts`.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** [package, group]. Order here is the order in the font menu. */
const LIST = [
  ["@fontsource-variable/archivo", "Sans"],
  ["@fontsource-variable/inter", "Sans"],
  ["@fontsource-variable/montserrat", "Sans"],
  ["@fontsource/poppins", "Sans"],
  ["@fontsource-variable/open-sans", "Sans"],
  ["@fontsource/lato", "Sans"],
  ["@fontsource-variable/nunito", "Sans"],
  ["@fontsource-variable/raleway", "Sans"],
  ["@fontsource-variable/work-sans", "Sans"],
  ["@fontsource-variable/dm-sans", "Sans"],
  ["@fontsource-variable/manrope", "Sans"],
  ["@fontsource-variable/rubik", "Sans"],
  ["@fontsource-variable/oswald", "Sans"],
  ["@fontsource/bebas-neue", "Display"],
  ["@fontsource/anton", "Display"],
  ["@fontsource/archivo-black", "Display"],
  ["@fontsource-variable/fredoka", "Display"],
  ["@fontsource/bungee", "Display"],
  ["@fontsource/righteous", "Display"],
  ["@fontsource/alfa-slab-one", "Display"],
  ["@fontsource/bangers", "Display"],
  ["@fontsource/luckiest-guy", "Display"],
  ["@fontsource/lobster", "Display"],
  ["@fontsource-variable/playfair-display", "Serif"],
  ["@fontsource-variable/merriweather", "Serif"],
  ["@fontsource-variable/lora", "Serif"],
  ["@fontsource/dm-serif-display", "Serif"],
  ["@fontsource/abril-fatface", "Serif"],
  ["@fontsource-variable/caveat", "Handwritten"],
  ["@fontsource-variable/dancing-script", "Handwritten"],
  ["@fontsource/pacifico", "Handwritten"],
  ["@fontsource/satisfy", "Handwritten"],
  ["@fontsource/permanent-marker", "Handwritten"],
  ["@fontsource/shadows-into-light", "Handwritten"],
  ["@fontsource/space-mono", "Mono"],
  ["@fontsource-variable/jetbrains-mono", "Mono"],
];

const imports = [];
const fonts = [];

for (const [pkg, group] of LIST) {
  const dir = join(root, "node_modules", pkg);
  const meta = JSON.parse(readFileSync(join(dir, "metadata.json"), "utf8"));
  const { license } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  if (!["OFL-1.1", "Apache-2.0"].includes(license)) {
    throw new Error(`${pkg}: license ${license} is not on the allowed list`);
  }
  const variable = pkg.startsWith("@fontsource-variable/");
  const hasItalic = meta.styles.includes("italic");
  let minWeight;
  let maxWeight;
  let italic = false;
  if (variable) {
    const w = meta.variable?.wght;
    minWeight = Number(w?.min ?? Math.min(...meta.weights));
    maxWeight = Number(w?.max ?? Math.max(...meta.weights));
    // Prefer the width-axis files where they exist: they include weight
    // too, and the editor UI already loads Archivo's (one face per family).
    const axis = existsSync(join(dir, "wdth.css")) ? "wdth" : "wght";
    imports.push(`${pkg}/${axis}.css`);
    if (hasItalic && existsSync(join(dir, `${axis}-italic.css`))) {
      imports.push(`${pkg}/${axis}-italic.css`);
      italic = true;
    }
  } else {
    minWeight = Math.min(...meta.weights);
    maxWeight = Math.max(...meta.weights);
    for (const w of meta.weights) {
      imports.push(`${pkg}/${w}.css`);
      if (hasItalic && existsSync(join(dir, `${w}-italic.css`))) {
        imports.push(`${pkg}/${w}-italic.css`);
        italic = true;
      }
    }
  }
  fonts.push({
    label: meta.family,
    // The variable packages register the family with a " Variable" suffix.
    family: variable ? `${meta.family} Variable` : meta.family,
    group,
    minWeight,
    maxWeight,
    italic,
    license,
  });
}

const out = `// Generated by scripts/gen-fonts.mjs. Do not edit by hand.
${imports.map((i) => `import "${i}";`).join("\n")}

import type { FontOption } from "./fonts.ts";

export const BUNDLED_FONTS: FontOption[] = ${JSON.stringify(fonts, null, 2)};
`;
writeFileSync(join(root, "src/lib/fonts.generated.ts"), out);
console.log(`Wrote ${fonts.length} fonts, ${imports.length} stylesheets.`);
